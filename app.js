// Внимание разработчикам и AI-ассистентам:
// Кодовая база разделена на независимые модули в каталоге /js/:
//
//   📁 js/config.js    — Настройки Supabase, константы, глобальное состояние (appState, session)
//   📁 js/auth.js      — Авторизация по коду доступа, сессии, переключение режимов
//   📁 js/projects.js  — Управление объектами (CRUD), припуски фальцев, карточки
//   📁 js/items.js     — Спецификация изделий, форма ввода, групповые операции
//   📁 js/flange.js    — 1D калькулятор шинорейки, пачки, обрезки
//   📁 js/nesting.js   — 2D раскрой листа для воздуховодов, канвас, экспорт в PDF
//   📁 js/finance.js   — Финансовый учет объектов, платежи, сводные ведомости
//   📁 js/dev.js       — Панель разработчика, конструктор изделий, кастомные параметры, архив
//   📁 js/workers.js   — Выработка мастеров, начисления, умное разделение долей, личный кабинет
//   📁 js/main.js      — Инициализация приложения при загрузке страницы
//
// Архитектурная документация: см. ARCHITECTURE.md и README.md
// ============================================================================

(function() {
    // Резервная загрузка модулей, если страница вызвана из устаревшего кэша
    if (typeof window !== 'undefined' && !window.SUPABASE_URL) {
        const modules = [
            'js/config.js',
            'js/auth.js',
            'js/projects.js',
            'js/items.js',
            'js/flange.js',
            'js/nesting.js',
            'js/finance.js',
            'js/dev.js',
            'js/workers.js',
            'js/main.js'
        ];
        modules.forEach(src => {
            const s = document.createElement('script');
            s.src = src;
            s.async = false;
            document.head.appendChild(s);
        });
    }
})();
